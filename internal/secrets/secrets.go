// Package secrets stores per-repository secrets encrypted with AES-256-GCM.
// Each sealed value is bound to its repository and name, so a value moved
// to another row in the database no longer decrypts.
package secrets

import (
	"context"
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"encoding/base64"
	"errors"
	"fmt"
	"regexp"
	"strings"

	"github.com/sidumandr/cisid/internal/db"
	"github.com/sidumandr/cisid/pkg/models"
)

const (
	// KeySize is the length of the AES-256 key in bytes.
	KeySize = 32
	// MaxValueBytes limits a secret's size.
	MaxValueBytes = 64 << 10
	maxNameLen    = 100
)

var (
	// ErrInvalidKey is returned for a key that is not 32 base64-encoded bytes.
	ErrInvalidKey = errors.New("invalid secret key")
	// ErrInvalidName is returned for a name that cannot be an environment variable.
	ErrInvalidName = errors.New("invalid secret name")
	// ErrTooLarge is returned for a value over MaxValueBytes.
	ErrTooLarge = errors.New("secret too large")
	// ErrNotFound is returned when a secret does not exist.
	ErrNotFound = errors.New("secret not found")
	// ErrCorrupt is returned when a stored value cannot be decrypted.
	ErrCorrupt = errors.New("secret cannot be decrypted")

	nameRe = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)
)

// ParseKey decodes a base64 key, as generated by `openssl rand -base64 32`.
func ParseKey(s string) ([]byte, error) {
	key, err := base64.StdEncoding.DecodeString(strings.TrimSpace(s))
	if err != nil {
		return nil, fmt.Errorf("%w: %w", ErrInvalidKey, err)
	}
	if len(key) != KeySize {
		return nil, fmt.Errorf("%w: got %d bytes, want %d", ErrInvalidKey, len(key), KeySize)
	}
	return key, nil
}

// ValidateName checks that name can be used as an environment variable and
// is not reserved for cisid.
func ValidateName(name string) error {
	switch {
	case len(name) > maxNameLen:
		return fmt.Errorf("%w: %q is longer than %d characters", ErrInvalidName, name, maxNameLen)
	case !nameRe.MatchString(name):
		return fmt.Errorf("%w: %q must be letters, digits and '_', not starting with a digit", ErrInvalidName, name)
	case name == "CI" || name == "CISID" || strings.HasPrefix(name, "CISID_"):
		return fmt.Errorf("%w: %q is reserved", ErrInvalidName, name)
	}
	return nil
}

// Cipher seals and opens secret values.
type Cipher struct {
	aead cipher.AEAD
}

// NewCipher returns a Cipher for a 32-byte key.
func NewCipher(key []byte) (*Cipher, error) {
	if len(key) != KeySize {
		return nil, fmt.Errorf("%w: got %d bytes, want %d", ErrInvalidKey, len(key), KeySize)
	}
	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, fmt.Errorf("create cipher: %w", err)
	}
	aead, err := cipher.NewGCM(block)
	if err != nil {
		return nil, fmt.Errorf("create cipher: %w", err)
	}
	return &Cipher{aead: aead}, nil
}

// Seal encrypts value for repo and name with a random nonce.
func (c *Cipher) Seal(repo, name, value string) ([]byte, error) {
	nonce := make([]byte, c.aead.NonceSize())
	if _, err := rand.Read(nonce); err != nil {
		return nil, fmt.Errorf("generate nonce: %w", err)
	}
	return c.aead.Seal(nonce, nonce, []byte(value), aad(repo, name)), nil
}

// Open decrypts a value sealed for repo and name.
func (c *Cipher) Open(repo, name string, sealed []byte) (string, error) {
	n := c.aead.NonceSize()
	if len(sealed) < n {
		return "", fmt.Errorf("%w: %s/%s", ErrCorrupt, repo, name)
	}
	plain, err := c.aead.Open(nil, sealed[:n], sealed[n:], aad(repo, name))
	if err != nil {
		return "", fmt.Errorf("%w: %s/%s", ErrCorrupt, repo, name)
	}
	return string(plain), nil
}

func aad(repo, name string) []byte {
	return []byte(repo + "\x00" + name)
}

// Store keeps sealed values. *db.Store satisfies it.
type Store interface {
	PutSecret(ctx context.Context, repo, name string, sealed []byte) error
	DeleteSecret(ctx context.Context, repo, name string) (bool, error)
	SecretNames(ctx context.Context, repo string) ([]models.SecretInfo, error)
	SealedSecrets(ctx context.Context, repo string, names []string) (map[string][]byte, error)
}

var _ Store = (*db.Store)(nil)

// Vault encrypts secrets on the way into a Store and decrypts them on the
// way out.
type Vault struct {
	store  Store
	cipher *Cipher
}

// NewVault returns a Vault.
func NewVault(store Store, c *Cipher) *Vault {
	return &Vault{store: store, cipher: c}
}

// Set stores value as secret name of repo, replacing an existing one.
func (v *Vault) Set(ctx context.Context, repo, name, value string) error {
	if err := ValidateName(name); err != nil {
		return err
	}
	if len(value) > MaxValueBytes {
		return fmt.Errorf("%w: %d bytes, at most %d", ErrTooLarge, len(value), MaxValueBytes)
	}
	sealed, err := v.cipher.Seal(repo, name, value)
	if err != nil {
		return err
	}
	return v.store.PutSecret(ctx, repo, name, sealed)
}

// Delete removes secret name of repo.
func (v *Vault) Delete(ctx context.Context, repo, name string) error {
	found, err := v.store.DeleteSecret(ctx, repo, name)
	if err != nil {
		return err
	}
	if !found {
		return fmt.Errorf("%w: %s/%s", ErrNotFound, repo, name)
	}
	return nil
}

// List returns the secrets of repo without their values.
func (v *Vault) List(ctx context.Context, repo string) ([]models.SecretInfo, error) {
	return v.store.SecretNames(ctx, repo)
}

// Secrets returns the values of the named secrets of repo. A missing
// secret is ErrNotFound.
func (v *Vault) Secrets(ctx context.Context, repo string, names []string) (map[string]string, error) {
	sealed, err := v.store.SealedSecrets(ctx, repo, names)
	if err != nil {
		return nil, err
	}
	values := make(map[string]string, len(names))
	for _, name := range names {
		s, ok := sealed[name]
		if !ok {
			return nil, fmt.Errorf("%w: %s is not set for %s", ErrNotFound, name, repo)
		}
		value, err := v.cipher.Open(repo, name, s)
		if err != nil {
			return nil, err
		}
		values[name] = value
	}
	return values, nil
}
